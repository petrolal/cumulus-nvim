-- TetraVim Native Lazy Bootstrapper (Story 1.2)

local lazypath = vim.fn.stdpath("data") .. "/lazy/lazy.nvim"

if not vim.uv.fs_stat(lazypath) then
  local lazyrepo = "https://github.com/folke/lazy.nvim.git"
  local out = vim.fn.system({ "git", "clone", "--filter=blob:none", "--branch=stable", lazyrepo, lazypath })
  if vim.v.shell_error ~= 0 then
    vim.api.nvim_echo({
      { "Failed to clone lazy.nvim:\n", "ErrorMsg" },
      { out, "WarningMsg" },
      { "\nPress any key to exit..." },
    }, true, {})
    vim.fn.getchar()
    os.exit(1)
  end
end

vim.opt.rtp:prepend(lazypath)

require("lazy").setup({
  spec = {
    { import = "tetravim.plugins" },
  },
  defaults = {
    lazy = false,
    version = false,
  },
  -- No implicit update checks. An enterprise setup wants a deterministic,
  -- proxy-friendly startup: `lazy-lock.json` is the source of truth and
  -- updates happen on purpose via `:Lazy update`. `version = false` above
  -- only means "no per-plugin semver pin" -- the lockfile still pins commits.
  checker = {
    enabled = false,
  },
  performance = {
    rtp = {
      disabled_plugins = {
        "gzip",
        "tarPlugin",
        "tohtml",
        "tutor",
        "zipPlugin",
      },
    },
  },
})
